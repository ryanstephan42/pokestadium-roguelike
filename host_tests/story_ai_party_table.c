/* PURE: emits every canonical campaign party, built by sc_make_mon, as a C table. */
#include <stdio.h>
#include "src/story/sc_core.h"
#include "src/story/sc_data.h"

int main(void) {
    unsigned e, v, s, i, rows = 0, teams = 0;
    RlMon mon;
    printf("/* generated by host_tests/story_ai_party_table.c */\n");
    printf("static const SweepMon sweep_mons[] = {\n");
    for (e = 0; e < sc_catalog.count; e++) {
        const ScEncounter *encounter = &sc_catalog.encounters[e];
        if (!encounter->variants || encounter->variants > 3) return 2;
        for (v = 0; v < encounter->variants; v++) {
            const ScTeam *team = &encounter->teams[v];
            if (team->count < 1 || team->count > 6) {
                fprintf(stderr, "%s/%u: count %u\n", encounter->id, v, team->count);
                return 3;
            }
            teams++;
            for (s = 0; s < team->count; s++) {
                if (sc_make_mon(&sc_catalog, &team->mons[s], 0, &mon) != SC_OK) {
                    fprintf(stderr, "%s/%u/%u: make_mon refused\n", encounter->id, v, s);
                    return 4;
                }
                printf("  {%u,%u,%u,%u,%u,%u,{%u,%u,%u,%u},{%u,%u,%u,%u},"
                       "%u,{%u,%u,%u,%u,%u}},\n",
                       e, v, s, team->count, encounter->kind, mon.species,
                       mon.moves[0], mon.moves[1], mon.moves[2], mon.moves[3],
                       mon.max_pp[0], mon.max_pp[1], mon.max_pp[2], mon.max_pp[3],
                       mon.level, mon.max_hp, mon.current_stats[1],
                       mon.current_stats[2], mon.current_stats[3],
                       mon.current_stats[4]);
                for (i = 0; i < 4; i++)
                    if (mon.moves[i] > 165) return 5;
                rows++;
            }
        }
    }
    printf("};\nenum { SWEEP_ROWS = %u, SWEEP_TEAMS = %u, SWEEP_ENCOUNTERS = %u };\n",
           rows, teams, (unsigned)sc_catalog.count);
    return 0;
}
